"""Regenerate `vectors/ledger_receipt.json`. Deterministic; the output is committed.

The Azure SDK bases are kept as they are in the file. The synthetic base is rebuilt from
fixed keys with deterministic ECDSA, and every case is derived from the bases.
"""

import base64
import copy
import datetime
import json
from collections.abc import Callable
from pathlib import Path
from typing import Any

from azure.confidentialledger.receipt import compute_claims_digest, verify_receipt
from cryptography import x509
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec, utils
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat
from cryptography.x509.oid import NameOID
from fourth_crypto import canonicalize, sha256

OUT = Path(__file__).resolve().parents[2] / "vectors" / "ledger_receipt.json"
SDK_PREFIX = "azure_sdk_"
NOT_BEFORE = datetime.datetime(2026, 1, 1, tzinfo=datetime.UTC)
NOT_AFTER = datetime.datetime(2026, 4, 1, tzinfo=datetime.UTC)
SERVICE = "Fourth Test Service"
VERDICT = {"decision": "goal_stands", "incident": "m1-73", "match": "Northbridge v Eastvale"}

Receipt = dict[str, Any]
Base = dict[str, Any]


def _key(label: str) -> ec.EllipticCurvePrivateKey:
    seed = int.from_bytes(sha256(f"fourth-proofs/{label}".encode()))
    return ec.derive_private_key(seed, ec.SECP384R1())


def _cert(
    subject: str,
    key: ec.EllipticCurvePrivateKey,
    issuer_key: ec.EllipticCurvePrivateKey,
    serial: int,
) -> str:
    cert = (
        x509.CertificateBuilder()
        .subject_name(x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, subject)]))
        .issuer_name(x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, SERVICE)]))
        .public_key(key.public_key())
        .serial_number(serial)
        .not_valid_before(NOT_BEFORE)
        .not_valid_after(NOT_AFTER)
        .add_extension(
            x509.BasicConstraints(ca=subject == SERVICE, path_length=None), critical=True
        )
        .sign(issuer_key, hashes.SHA384(), ecdsa_deterministic=True)
    )
    return cert.public_bytes(Encoding.PEM).decode()


def _synthetic() -> Base:
    """A receipt whose node is endorsed by a previous service identity, then the current one."""
    current, previous, node = _key("service-current"), _key("service-previous"), _key("node")
    service_pem = _cert(SERVICE, current, current, 1)
    endorsement_pem = _cert(SERVICE, previous, current, 2)
    node_pem = _cert("Fourth Test Node", node, previous, 3)

    verdict = canonicalize(VERDICT)
    claims: list[dict[str, Any]] = [
        {
            "kind": "LedgerEntry",
            "ledgerEntry": {
                "collectionId": "subledger:0",
                "contents": verdict.decode(),
                "protocol": "LedgerEntryV1",
                "secretKey": base64.b64encode(sha256(b"fourth-proofs/claims-secret")).decode(),
            },
        },
        {
            "kind": "ClaimDigest",
            "digest": {"protocol": "LedgerEntryV1", "value": sha256(verdict).hex()},
        },
    ]
    leaf = {
        "claimsDigest": compute_claims_digest(claims),
        "commitEvidence": "ce:2.7:" + sha256(b"fourth-proofs/commit-evidence").hex(),
        "writeSetDigest": sha256(b"fourth-proofs/write-set").hex(),
    }
    proof = [
        {"left": sha256(b"fourth-proofs/node-0").hex()},
        {"right": sha256(b"fourth-proofs/node-1").hex()},
        {"left": sha256(b"fourth-proofs/node-2").hex()},
    ]
    current_hash = sha256(
        bytes.fromhex(leaf["writeSetDigest"])
        + sha256(leaf["commitEvidence"].encode())
        + bytes.fromhex(leaf["claimsDigest"])
    )
    for element in proof:
        if "left" in element:
            current_hash = sha256(bytes.fromhex(element["left"]) + current_hash)
        else:
            current_hash = sha256(current_hash + bytes.fromhex(element["right"]))
    signature = node.sign(current_hash, ec.ECDSA(utils.Prehashed(hashes.SHA256()), True))
    spki = node.public_key().public_bytes(Encoding.DER, PublicFormat.SubjectPublicKeyInfo)
    receipt = {
        "cert": node_pem,
        "leafComponents": leaf,
        "nodeId": sha256(spki).hex(),
        "proof": proof,
        "serviceEndorsements": [endorsement_pem],
        "signature": base64.b64encode(signature).decode(),
    }
    return {
        "source": "synthetic, generated by libs/proofs/py/scripts/gen_ledger_mutations.py",
        "receipt": receipt,
        "service_certificate": service_pem,
        "application_claims": claims,
    }


def _flip(data: bytes, index: int) -> bytes:
    out = bytearray(data)
    out[index] ^= 0x01
    return bytes(out)


def _flip_hex(text: str, index: int) -> str:
    return _flip(bytes.fromhex(text), index).hex()


def _flip_b64(text: str, index: int) -> str:
    return base64.b64encode(_flip(base64.b64decode(text), index)).decode()


def _pem(der: bytes) -> str:
    body = base64.b64encode(der).decode()
    lines = [body[i : i + 64] for i in range(0, len(body), 64)]
    return "-----BEGIN CERTIFICATE-----\n" + "\n".join(lines) + "\n-----END CERTIFICATE-----\n"


def _cert_offsets(pem: str) -> dict[str, int]:
    """Byte offsets inside the DER certificate: one per field family that a verifier reads."""
    cert = x509.load_pem_x509_certificate(pem.encode())
    der = cert.public_bytes(Encoding.DER)
    spki = cert.public_key().public_bytes(Encoding.DER, PublicFormat.SubjectPublicKeyInfo)
    subject = cert.subject.public_bytes()
    tbs = cert.tbs_certificate_bytes
    after_version = der.find(b"\xa0\x03\x02\x01\x02", der.find(tbs)) + 5
    return {
        "serial": after_version + 2,
        "subject": der.rfind(subject) + len(subject) - 1,
        "public_key": der.find(spki) + len(spki) - 1,
        "signature_algorithm": der.find(tbs) + len(tbs) + 11,
        "signature_unused_bits": len(der) - len(cert.signature) - 1,
        "signature": len(der) - 1,
    }


def _flip_pem(pem: str, index: int) -> str:
    der = x509.load_pem_x509_certificate(pem.encode()).public_bytes(Encoding.DER)
    return _pem(_flip(der, index))


Mutation = Callable[[Receipt], None]


def _set(path: str, change: Callable[[Any], Any]) -> Mutation:
    def apply(receipt: Receipt) -> None:
        *parents, last = path.split(".")
        target: Any = receipt
        for part in parents:
            target = target[int(part)] if part.isdigit() else target[part]
        key: Any = int(last) if last.isdigit() else last
        target[key] = change(target[key])

    return apply


def _swap_side(receipt: Receipt) -> None:
    ((side, value),) = receipt["proof"][0].items()
    receipt["proof"][0] = {("right" if side == "left" else "left"): value}


def _receipt_mutations(receipt: Receipt) -> dict[str, Mutation]:
    last = len(receipt["proof"]) - 1
    side = next(iter(receipt["proof"][last]))
    mutations: dict[str, Mutation] = {
        "leaf_write_set_digest_first_byte": _set(
            "leafComponents.writeSetDigest", lambda v: _flip_hex(v, 0)
        ),
        "leaf_write_set_digest_last_byte": _set(
            "leafComponents.writeSetDigest", lambda v: _flip_hex(v, -1)
        ),
        "leaf_claims_digest_byte": _set("leafComponents.claimsDigest", lambda v: _flip_hex(v, 7)),
        "leaf_commit_evidence_byte": _set(
            "leafComponents.commitEvidence", lambda v: _flip(v.encode(), -1).decode()
        ),
        "proof_first_node_byte": _set(
            f"proof.0.{next(iter(receipt['proof'][0]))}", lambda v: _flip_hex(v, 0)
        ),
        "proof_last_node_byte": _set(f"proof.{last}.{side}", lambda v: _flip_hex(v, -1)),
        "proof_side_swapped": _swap_side,
        "proof_node_dropped": lambda r: r["proof"].pop(),
        "signature_r_byte": _set("signature", lambda v: _flip_b64(v, 10)),
        "signature_last_byte": _set("signature", lambda v: _flip_b64(v, -1)),
        "node_id_byte": _set("nodeId", lambda v: _flip_hex(v, 0)),
    }
    for field, offset in _cert_offsets(receipt["cert"]).items():
        mutations[f"node_cert_{field}_byte"] = _set("cert", lambda v, o=offset: _flip_pem(v, o))
    return mutations


def _case(
    name: str, base: Base, *, valid: bool, mutate: Mutation | None = None, **changes: Any
) -> dict[str, Any]:
    """A case from `base`; `changes` replaces `service_certificate` or `application_claims`."""
    receipt = copy.deepcopy(base["receipt"])
    if mutate is not None:
        mutate(receipt)
    case = {
        "name": name,
        "receipt": receipt,
        "service_certificate": base["service_certificate"],
        "application_claims": base["application_claims"],
        **changes,
        "valid": valid,
    }
    return copy.deepcopy(case)


def _claims_mutations(claims: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    out: dict[str, list[dict[str, Any]]] = {}
    for index, claim in enumerate(claims):
        if claim["kind"] == "LedgerEntry":
            entry = claim["ledgerEntry"]
            for field in ("collectionId", "contents"):
                changed = copy.deepcopy(claims)
                changed[index]["ledgerEntry"][field] = _flip(entry[field].encode(), -1).decode()
                out[f"claims_{index}_{field}_byte"] = changed
            changed = copy.deepcopy(claims)
            changed[index]["ledgerEntry"]["secretKey"] = _flip_b64(entry["secretKey"], 0)
            out[f"claims_{index}_secret_key_byte"] = changed
            changed = copy.deepcopy(claims)
            changed[index]["ledgerEntry"]["protocol"] = "LedgerEntryV2"
            out[f"claims_{index}_unknown_protocol"] = changed
        else:
            changed = copy.deepcopy(claims)
            changed[index]["digest"]["value"] = _flip_hex(claim["digest"]["value"], 0)
            out[f"claims_{index}_digest_value_byte"] = changed
    out["claims_duplicated"] = [*copy.deepcopy(claims), *copy.deepcopy(claims)]
    if len(claims) > 1:
        out["claims_reordered"] = copy.deepcopy(claims[::-1])
        out["claims_truncated"] = copy.deepcopy(claims[:1])
    return out


def _cases(bases: dict[str, Base]) -> list[dict[str, Any]]:
    sdk_1, sdk_2 = bases["azure_sdk_receipt_1"], bases["azure_sdk_receipt_2"]
    synthetic = bases["synthetic_receipt_with_endorsement"]
    other_service = {
        "azure_sdk_receipt_1": sdk_2["service_certificate"],
        "azure_sdk_receipt_2": sdk_1["service_certificate"],
        "azure_sdk_receipt_with_claims": sdk_1["service_certificate"],
        "synthetic_receipt_with_endorsement": bases["azure_sdk_receipt_with_claims"][
            "service_certificate"
        ],
    }
    cases: list[dict[str, Any]] = []
    for name, base in bases.items():
        cases.append(_case(f"{name}/valid", base, valid=True))
        claims = base["application_claims"]
        if claims is not None:
            cases.append(_case(f"{name}/claims_omitted", base, valid=True, application_claims=None))
            for label, changed in _claims_mutations(claims).items():
                cases.append(
                    _case(f"{name}/{label}", base, valid=False, application_claims=changed)
                )
        if name not in other_service:
            continue
        for label, mutate in _receipt_mutations(base["receipt"]).items():
            cases.append(_case(f"{name}/{label}", base, valid=False, mutate=mutate))
        cases.append(
            _case(f"{name}/node_id_absent", base, valid=True, mutate=lambda r: r.pop("nodeId"))
        )
        cases.append(
            _case(
                f"{name}/wrong_service_certificate",
                base,
                valid=False,
                service_certificate=other_service[name],
            )
        )

    unrelated = sdk_2["service_certificate"]
    cases.append(
        _case(
            "azure_sdk_receipt_1/unexpected_endorsement",
            sdk_1,
            valid=False,
            mutate=_set("serviceEndorsements", lambda _: [unrelated]),
        )
    )
    cases.append(
        _case(
            "azure_sdk_receipt_1/claims_for_zero_claims_digest",
            sdk_1,
            valid=False,
            application_claims=bases["azure_sdk_receipt_with_claim_digest"]["application_claims"],
        )
    )
    endorsement = synthetic["receipt"]["serviceEndorsements"][0]
    chain_mutations: dict[str, Mutation] = {
        "endorsements_empty": _set("serviceEndorsements", lambda _: []),
        "endorsements_absent": lambda r: r.pop("serviceEndorsements"),
        "endorsement_replaced_by_service_certificate": _set(
            "serviceEndorsements", lambda _: [synthetic["service_certificate"]]
        ),
        "endorsement_repeated": _set("serviceEndorsements", lambda v: [*v, *v]),
    }
    for label, mutate in chain_mutations.items():
        cases.append(
            _case(
                f"synthetic_receipt_with_endorsement/{label}", synthetic, valid=False, mutate=mutate
            )
        )
    for field, offset in _cert_offsets(endorsement).items():
        cases.append(
            _case(
                f"synthetic_receipt_with_endorsement/endorsement_{field}_byte",
                synthetic,
                valid=False,
                mutate=_set("serviceEndorsements.0", lambda v, o=offset: _flip_pem(v, o)),
            )
        )
    cases.append(
        _case(
            "synthetic_receipt_with_endorsement/previous_identity_as_service_certificate",
            synthetic,
            valid=False,
            service_certificate=endorsement,
        )
    )
    return cases


def _record_sdk_outcome(case: dict[str, Any]) -> dict[str, Any]:
    """Note where the Azure SDK verifier accepts what these verifiers reject."""
    try:
        verify_receipt(
            copy.deepcopy(case["receipt"]),
            case["service_certificate"],
            application_claims=copy.deepcopy(case["application_claims"]),
        )
        accepted = True
    except ValueError:
        accepted = False
    return case if accepted is case["valid"] else {**case, "azure_sdk_valid": accepted}


def main() -> None:
    document = json.loads(OUT.read_text(encoding="utf-8"))
    bases: dict[str, Base] = {
        name: base for name, base in document["bases"].items() if name.startswith(SDK_PREFIX)
    }
    bases["synthetic_receipt_with_endorsement"] = _synthetic()
    document["bases"] = bases
    document["cases"] = [_record_sdk_outcome(case) for case in _cases(bases)]
    OUT.write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
